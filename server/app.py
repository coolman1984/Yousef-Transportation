def is_admin(u):
    """Administrator = may manage users. Monitoring, devices and conflicts need this, checked on every request."""
    return bool(u) and 'users.manage' in u['perms']


FAILED = {}  # ip -> times of recent failed logins (this PC only)
FAILED_LOCK = threading.Lock()


def too_many_failures(ip, add=False):
    """More than 10 failed logins (password or link) from one address within a minute: refuse quickly for a while,
    without the slow password check and without filling the logs of every PC."""
    t = time.time()
    with FAILED_LOCK:
        recent = [x for x in FAILED.get(ip, []) if t - x < 60]
        if add:
            recent.append(t)
        if recent:
            FAILED[ip] = recent[-50:]
        else:
            FAILED.pop(ip, None)
        if len(FAILED) > 5000:  # never grow without limit
            FAILED.clear()
        return len(recent) > 10


class Handler(BaseHTTPRequestHandler):
    server_version = 'TripOrders/1.0'
    protocol_version = 'HTTP/1.1'
    timeout = max(5, int(CFG.get('idle_timeout_seconds') or 60))  # a connection that stays silent is closed
    u = None  # the logged-in user of this request (set by login_required)
    _read = False  # True once the request body was read

    # ------------------------------------------------------------ plumbing
    def log_message(self, fmt, *args):
        pass  # API calls are logged explicitly below; static files are not worth logging

    @property
    def user(self):
        return self.u['display'] if self.u else 'Not logged in'

    @property
    def log_path(self):
        """The address for logs: the secret part of a personal link is never written anywhere."""
        return '/k/…' if self.path.startswith('/k/') else self.path

    @property
    def ip(self):
        return self.client_address[0]

    @property
    def token(self):
        for part in (self.headers.get('Cookie') or '').split(';'):
            k, _, v = part.strip().partition('=')
            if k == COOKIE:
                return v
        return ''

    def login_required(self, touch=True):
        self.u = AUTH.session(self.token, self.ip, touch) or demo_user()
        if not self.u:
            raise NotLoggedIn()
        return self.u

    def can(self, *perms):
        return bool(self.u) and any(p in self.u['perms'] for p in perms)

    def need(self, *perms):
        if not self.can(*perms):
            raise Forbidden('You do not have permission for this. Ask the administrator for: "' + PERM_LABEL[perms[0]] + '".', 'err.needPerm', perm=perms[0])

    def send(self, code, body=b'', ctype='application/json', headers=None):
        if isinstance(body, (dict, list)):
            body = json.dumps(body, ensure_ascii=False).encode('utf-8')
        elif isinstance(body, str):
            body = body.encode('utf-8')
        self.send_response(code)
        unread = self.command == 'POST' and not self._read and (self.headers.get('Content-Length') or '0').strip() != '0'  # also a damaged length
        if code >= 400 or unread:  # the request body may be unread - don't reuse this connection
            self.close_connection = True
            self.send_header('Connection', 'close')
        self.send_header('Content-Type', ctype)
        self.send_header('Content-Length', str(len(body)))
        self.send_header('X-Content-Type-Options', 'nosniff')
        self.send_header('X-Frame-Options', 'DENY')
        self.send_header('Referrer-Policy', 'same-origin')
        if ctype.startswith('text/html'):
            self.send_header('Content-Security-Policy', CSP)
        headers = dict(headers or {})
        if self.path.startswith('/api/'):
            headers.setdefault('Cache-Control', 'no-store')
        for k, v in headers.items():
            self.send_header(k, v)
        self.end_headers()
        if self.command != 'HEAD':
            self.wfile.write(body)
        if code == 200 and self.command == 'POST' and self.u and ASSIST is not None:
            act = assist_mod.ACTIONS.get(self.path.split('?')[0])
            if act:
                try:
                    ASSIST.note_action(self.u, *act)          # a count of confirmed actions; only with the installation's and the person's consent
                except Exception:  # noqa: BLE001 - telemetry never fails a request
                    pass

